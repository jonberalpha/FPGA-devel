#!/usr/bin/env python3
"""Generate the 80x30 text screen (hdl/screen.hex) and the dynamic field positions (hdl/screen_fields.vh).

Template syntax: {name:len} marks a dynamic field of len characters that text_gen.v fills at runtime.
"""
import re

COLS, ROWS = 80, 30

TEMPLATE = {
    1:  "  TANG PRIMER 20K DOCK - PERIPHERAL DEMO",
    2:  "  ======================================",
    4:  "> uptime   : {uptime:6} s",
    5:  "> uart     : 115200 8N1, every 3 s, msg #{msgcnt:5}",
    6:  "> audio    : sine {freq:4} Hz   DIP2-5 = {dip:4}",
    8:  "> LED5 [S1] : {l5:3}",
    9:  "> LED4 [S2] : {l4:3}",
    10: "> LED3 [S3] : {l3:3}",
    12: "> ethernet : http://192.168.50.2/  requests {reqcnt:5}",
    13: "> eth link : {link:4}",
    14: "> usb      : stage 3 - mouse jiggler",
    15: "> {cur:1}",
}

screen = [[0x20] * COLS for _ in range(ROWS)]
fields = []
for row, text in TEMPLATE.items():
    col = 0
    for part in re.split(r"(\{\w+:\d+\})", text):
        m = re.fullmatch(r"\{(\w+):(\d+)\}", part)
        if m:
            fields.append((m.group(1).upper(), row, col, int(m.group(2))))
            col += int(m.group(2))
        else:
            for ch in part:
                screen[row][col] = ord(ch)
                col += 1

with open("hdl/screen.hex", "w") as f:
    for r in screen:
        for c in r:
            f.write("%02x\n" % c)

with open("hdl/screen_fields.vh", "w") as f:
    f.write("// Generated by tools/gen_screen.py - do not edit\n")
    for name, row, col, ln in fields:
        f.write("localparam F_%s_ROW = %d, F_%s_COL = %d, F_%s_LEN = %d;\n" % (name, row, name, col, name, ln))
print("fields:", fields)
