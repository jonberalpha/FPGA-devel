#!/usr/bin/env python3
"""Generate hdl/sine_lut.v: one quarter-wave sine table (64 entries, 16 bit signed amplitude)."""
import math, sys

N = 64
AMP = int(sys.argv[1]) if len(sys.argv) > 1 else 6000   # moderate volume, the amplifier is loud
dst = sys.argv[2] if len(sys.argv) > 2 else "hdl/sine_lut.v"

with open(dst, "w") as f:
    f.write("// Generated by tools/gen_sine.py - quarter wave, mid-point sampled, amplitude %d\n" % AMP)
    f.write("module sine_lut (input [5:0] idx, output reg [15:0] val);\n")
    f.write("  always @* case (idx)\n")
    for i in range(N):
        v = round(AMP * math.sin((i + 0.5) * math.pi / 2 / N))
        f.write("    6'd%d: val = 16'd%d;\n" % (i, v))
    f.write("    default: val = 16'd0;\n  endcase\nendmodule\n")
print("wrote", dst)
