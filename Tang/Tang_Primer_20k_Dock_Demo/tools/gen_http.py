#!/usr/bin/env python3
"""Generate the static HTTP response (headers + HTML) for the FPGA web server.

Writes hdl/http_page.hex (one byte per line) and hdl/http_page.vh (length and slot offsets).
The LED state words ("OFF"/"ON ") are 3 bytes each so Content-Length never changes.
"""

BODY = (
    "<!DOCTYPE html><html><head><meta charset=utf-8>"
    "<meta name=viewport content='width=device-width,initial-scale=1'>"
    "<title>Tang Primer 20K</title>"
    "<style>body{background:#012;color:#6f8;font:20px monospace;padding:16px}"
    "a{display:inline-block;margin:4px;padding:8px 18px;background:#6f8;color:#012;text-decoration:none}"
    "b{display:inline-block;width:3ch}</style></head><body>"
    "<h2>Tang Primer 20K Dock</h2>"
    "<p>LED5 <b>@@@</b> <a href=/l5/on>ON</a><a href=/l5/off>OFF</a></p>"
    "<p>LED4 <b>@@@</b> <a href=/l4/on>ON</a><a href=/l4/off>OFF</a></p>"
    "<p>LED3 <b>@@@</b> <a href=/l3/on>ON</a><a href=/l3/off>OFF</a></p>"
    "</body></html>"
)

head = ("HTTP/1.1 200 OK\r\nContent-Type: text/html\r\nContent-Length: %d\r\n"
        "Connection: close\r\n\r\n") % len(BODY)
page = head + BODY

# slot positions (LED5, LED4, LED3 in page order)
slots, pos = [], 0
while True:
    pos = page.find("@@@", pos)
    if pos < 0:
        break
    slots.append(pos)
    pos += 3
assert len(slots) == 3
page = page.replace("@@@", "OFF")
assert len(page) <= 1400

with open("hdl/http_page.hex", "w") as f:
    for ch in page:
        f.write("%02x\n" % ord(ch))
with open("hdl/http_page.vh", "w") as f:
    f.write("// Generated by tools/gen_http.py - do not edit\n")
    f.write("localparam PAGE_LEN = %d;\n" % len(page))
    f.write("localparam SLOT_L5 = %d, SLOT_L4 = %d, SLOT_L3 = %d;\n" % tuple(slots))
print("page", len(page), "bytes, slots", slots)
